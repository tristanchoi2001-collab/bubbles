"""사용자 답변(2026-10-23): 수평 채널, 기체·액체 유량을 L/min 단위로 잼. 0.3·0.7 mm는 저유량에서 팬케이크.
갭 H, 폭 W에서 겉보기 속도 j ↔ 체적 유량(mL/min)과, α·β 식에 필요한 β 정밀도(상대 2 %)가 요구하는 기체 유량 정밀도.
폭 W는 아직 모름 → 20 mm, 50 mm 두 경우.
"""
for W in (20e-3, 50e-3):
    print(f"\n### 폭 W = {W*1e3:.0f} mm")
    print("| H (mm) | j (m/s) | Q_L+Q_G 합 (mL/min) | β = 0.05일 때 Q_G (mL/min) | β = 0.2일 때 Q_G (mL/min) | β ±2 %에 필요한 Q_G 정밀도 (β 0.05 / 0.2, mL/min) |")
    print("|---|---|---|---|---|---|")
    for H in (0.3e-3, 0.7e-3, 1e-3):
        A = W * H
        for j in (0.05, 0.1, 0.2, 0.4):
            Q = j * A * 6e7          # m3/s -> mL/min
            qg1, qg2 = 0.05 * Q, 0.2 * Q
            print(f"| {H*1e3:g} | {j} | {Q:.1f} | {qg1:.2f} | {qg2:.1f} | ±{0.02*qg1:.3f} / ±{0.02*qg2:.2f} |")
# 표준 상태 유량(질량 유량계) -> 국소 실제 유량: 국소 절대압 p, 온도 T
for pg in (2, 10, 30):   # kPa 게이지
    p = 101.325 + pg
    print(f"국소 게이지압 {pg} kPa: 실제 유량 = 표준 유량 × {101.325/p:.3f} (온도 같다고 보면)")
