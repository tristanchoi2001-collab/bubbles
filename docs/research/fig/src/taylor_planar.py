"""거대 기포 영역(폭을 가로지르는 긴 기포) 후보 폐합: 평면 Taylor 흐름(Warnier 2010의 납작 유로판).
-dP/dx = (12 mu/H^2) j (L_s/L_u)  +  (f_b/V_b) (2 sigma/H) c Ca_b^(2/3)
  - 액체 슬러그: 포아죄유 흐름, 평균 속도 ≈ j(얇은 막이면).
  - 기포: 평면 Bretherton 앞뒤 메니스커스의 동적 압력 점프 합 (2 sigma/H)(3.88 + 1.13) Ca^(2/3), c = 5.01(깨끗)~12.63(굳음).
  - 기포 앞뒤 사이의 납작한 막 구간은 막이 멈춰 있어 압력 구배가 없다(1차 근사).
  - 입력은 모두 영상: 기포 통과 빈도 f_b, 속도 V_b, 단위 길이 L_u = V_b/f_b, 슬러그 길이 L_s.
"""
mu, sig = 1.002e-3, 0.0728
print("| H (mm) | j (m/s) | 슬러그 마찰 (kPa/m) | 기포 앞뒤 항 (kPa/m) | 기포 항 비율 |")
print("|---|---|---|---|---|")
Lu, frac_s = 0.03, 1 / 3      # 예: 단위 30 mm 중 액체 슬러그 1/3 (기포 20 mm)
for H in (0.3e-3, 0.7e-3, 1e-3):
    for j in (0.1, 0.3, 1.0):
        Vb = j                   # 얇은 막이면 V_b ≈ j
        Ca = mu * Vb / sig
        slug = 12 * mu * j / H**2 * frac_s
        caps = (1 / Lu) * (2 * sig / H) * 5.01 * Ca ** (2 / 3)
        print(f"| {H*1e3:g} | {j} | {slug/1e3:.2f} | {caps/1e3:.2f} | {caps/(slug+caps):.2f} |")
